#![cfg_attr(all(windows, not(debug_assertions)), windows_subsystem = "windows")]
//! ConWatch desktop shell: native window (system webview) + tray icon showing live speed.

use conwatch_core::event::Event as NetEvent;
use conwatch_core::traffic::TrafficSampler;
use std::time::{Duration, Instant};
use tao::dpi::LogicalSize;
use tao::event::{Event, StartCause, WindowEvent};
use tao::event_loop::{ControlFlow, EventLoopBuilder};
use tao::window::WindowBuilder;
use tray_icon::menu::{Menu, MenuEvent, MenuItem};
use tray_icon::{Icon, TrayIconBuilder, TrayIconEvent};
use wry::{WebContext, WebView, WebViewBuilder};

const PORT: u16 = 8650;

fn human(bps: u64) -> String {
    let (mut v, mut i) = (bps as f64, 0);
    while v >= 1024.0 && i < 3 {
        v /= 1024.0;
        i += 1;
    }
    format!("{v:.1} {}/s", ["B", "KB", "MB", "GB"][i])
}

/// 64x64 RGBA of the app icon (generated by tools/make_icon.py).
const ICON_RGBA: &[u8] = include_bytes!("../assets/icon64.rgba");

fn tray_icon() -> Icon {
    Icon::from_rgba(ICON_RGBA.to_vec(), 64, 64).expect("tray icon")
}

fn window_icon() -> Option<tao::window::Icon> {
    tao::window::Icon::from_rgba(ICON_RGBA.to_vec(), 64, 64).ok()
}

/// Start the dashboard server. After an elevated relaunch the old instance may still hold the port
/// for a moment, so retry for a few seconds; otherwise attach to whatever already serves it.
fn start_server() -> String {
    let relaunched = std::env::args().any(|a| a == "--relaunch");
    let attempts = if relaunched { 40 } else { 1 };
    for i in 0..attempts {
        if let Ok(u) = conwatch_cli::serve::start(PORT) {
            return u;
        }
        if i + 1 < attempts {
            std::thread::sleep(Duration::from_millis(250));
        }
    }
    // Another instance (or the CLI) already serves the dashboard: just attach to it.
    format!("http://127.0.0.1:{PORT}")
}

fn main() {
    let url = start_server();

    let event_loop = EventLoopBuilder::new().build();
    let window = WindowBuilder::new()
        .with_title("ConWatch")
        .with_window_icon(window_icon())
        .with_inner_size(LogicalSize::new(1100.0, 760.0))
        .build(&event_loop)
        .expect("window");
    // WebView2 profile lives in %LOCALAPPDATA%\ConWatch (the install folder may be read-only).
    let mut web_ctx = WebContext::new(Some(conwatch_cli::data_dir().join("webview")));
    let mut webview: Option<WebView> = Some(WebViewBuilder::with_web_context(&mut web_ctx).with_url(&url).build(&window).expect("webview"));

    let menu = Menu::new();
    let show = MenuItem::new("Open ConWatch", true, None);
    let quit = MenuItem::new("Quit", true, None);
    let _ = menu.append_items(&[&show, &quit]);
    let (show_id, quit_id) = (show.id().clone(), quit.id().clone());
    let tray = TrayIconBuilder::new().with_menu(Box::new(menu)).with_tooltip("ConWatch").with_icon(tray_icon()).build().expect("tray");

    let mut sampler = TrafficSampler::new();
    event_loop.run(move |event, _, flow| {
        *flow = ControlFlow::WaitUntil(Instant::now() + Duration::from_secs(1));
        match event {
            Event::NewEvents(StartCause::ResumeTimeReached { .. }) | Event::NewEvents(StartCause::Init) => {
                if let NetEvent::TrafficSample { rx_bytes, tx_bytes, interval_ms } = sampler.sample() {
                    let (rx, tx) = (rx_bytes * 1000 / interval_ms, tx_bytes * 1000 / interval_ms);
                    let _ = tray.set_tooltip(Some(format!("ConWatch\n▼ {}  ▲ {}", human(rx), human(tx))));
                }
            }
            // Closing the window hides it to the tray; use the tray menu to quit.
            Event::WindowEvent { event: WindowEvent::CloseRequested, .. } => {
                // Free the web view (and its ~300 MB of helper processes) while ConWatch lives in the tray.
                window.set_visible(false);
                webview = None;
            }
            _ => {}
        }
        while let Ok(ev) = MenuEvent::receiver().try_recv() {
            if ev.id == show_id {
                if webview.is_none() {
                    webview = WebViewBuilder::with_web_context(&mut web_ctx).with_url(&url).build(&window).ok();
                }
                window.set_visible(true);
                window.set_focus();
            } else if ev.id == quit_id {
                *flow = ControlFlow::Exit;
            }
        }
        while let Ok(ev) = TrayIconEvent::receiver().try_recv() {
            if matches!(ev, TrayIconEvent::DoubleClick { .. }) {
                if webview.is_none() {
                    webview = WebViewBuilder::with_web_context(&mut web_ctx).with_url(&url).build(&window).ok();
                }
                window.set_visible(true);
                window.set_focus();
            }
        }
    });
}
