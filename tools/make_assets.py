"""Generates the embedded UI assets (run manually; outputs are committed).

  world map  : Natural Earth 110m countries (public domain) -> crates/conwatch-cli/ui/world.svg
  flags      : flagcdn.com 20px PNGs                         -> crates/conwatch-cli/ui/flags/<cc>.png + src/flags.rs

Usage: python tools/make_assets.py <countries.geojson> <flag-codes.json>
"""
import json, os, subprocess, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UI = os.path.join(ROOT, 'crates', 'conwatch-cli', 'ui')
W, H = 1000.0, 500.0
LAT_TOP, LAT_BOT = 84.0, -58.0  # crop Antarctica


def proj(lon, lat):
    x = (lon + 180.0) / 360.0 * W
    y = (LAT_TOP - lat) / (LAT_TOP - LAT_BOT) * H
    return x, y


def ring_path(ring):
    pts = [proj(lon, lat) for lon, lat in ring]
    out = []
    last = None
    for x, y in pts:
        p = (round(x, 1), round(y, 1))
        if p != last:
            out.append(p)
            last = p
    if len(out) < 3:
        return ''
    d = 'M' + ' '.join(f'{x:g} {y:g}' for x, y in out) + 'Z'
    return d


def area_centroid(ring):
    a = cx = cy = 0.0
    pts = [proj(lon, lat) for lon, lat in ring]
    for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
        c = x0 * y1 - x1 * y0
        a += c
        cx += (x0 + x1) * c
        cy += (y0 + y1) * c
    if abs(a) < 1e-9:
        return pts[0][0], pts[0][1], 0.0
    return cx / (3 * a), cy / (3 * a), abs(a / 2)


def make_map(geo):
    g = json.load(open(geo, encoding='utf-8'))
    paths = []
    for f in g['features']:
        p = f['properties']
        cc = p.get('ISO_A2_EH') or p.get('ISO_A2')
        if cc in (None, '-99', '-9'):
            cc = {'FRA': 'FR', 'NOR': 'NO', 'KOS': 'XK', 'SOL': '', 'CYN': 'CY'}.get(p.get('ADM0_A3'), '')
        if p.get('ADM0_A3') == 'ATA':
            continue
        geom = f['geometry']
        polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
        d = ''
        best = (0.0, 0.0, 0.0)
        for poly in polys:
            for i, ring in enumerate(poly):
                d += ring_path(ring)
            c = area_centroid(poly[0])
            if c[2] > best[2]:
                best = c
        if not d:
            continue
        name = p.get('NAME', '').replace('&', '&amp;').replace('"', '&quot;')
        paths.append(f'<path data-cc="{cc}" data-cx="{best[0]:.0f}" data-cy="{best[1]:.0f}" data-n="{name}" d="{d}"/>')
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W:g} {H:g}">' + ''.join(paths) + '</svg>'
    open(os.path.join(UI, 'world.svg'), 'w', encoding='utf-8', newline='\n').write(svg)
    print('world.svg', len(svg) // 1024, 'KB,', len(paths), 'countries')


def make_flags(codes_json):
    codes = sorted(k for k in json.load(open(codes_json)) if len(k) == 2)
    d = os.path.join(UI, 'flags')
    os.makedirs(d, exist_ok=True)
    total = 0
    got = []
    for cc in codes:
        path = os.path.join(d, cc + '.png')
        if not os.path.exists(path):
            req = urllib.request.Request(f'https://flagcdn.com/w20/{cc}.png', headers={'User-Agent': 'conwatch-assets'})
            try:
                open(path, 'wb').write(urllib.request.urlopen(req, timeout=30).read())
            except Exception as e:
                print('skip', cc, e)
                continue
        total += os.path.getsize(path)
        got.append(cc)
    rs = ['// @generated by tools/make_assets.py - flag PNGs (flagcdn.com), embedded in the binary.',
          'pub fn flag(cc: &str) -> Option<&\'static [u8]> {', '    Some(match cc {']
    for cc in got:
        rs.append(f'        "{cc}" => include_bytes!("../ui/flags/{cc}.png"),')
    rs += ['        _ => return None,', '    })', '}', '']
    open(os.path.join(ROOT, 'crates', 'conwatch-cli', 'src', 'flags.rs'), 'w', encoding='utf-8', newline='\n').write('\n'.join(rs))
    print(len(got), 'flags,', total // 1024, 'KB')


if __name__ == '__main__':
    make_map(sys.argv[1])
    make_flags(sys.argv[2])
